package com.iwhalecloud.byai.manager.domain.tenant.policy;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import static org.junit.jupiter.api.Assertions.*;

class TenantExecutionPolicyServiceTest {
    private final ObjectMapper mapper = new ObjectMapper();
    private JdbcTemplate jdbc;
    private TenantExecutionPolicyService service;
    private TransactionTemplate transaction;

    private com.fasterxml.jackson.databind.JsonNode policy(String override) throws Exception {
        var result = (com.fasterxml.jackson.databind.node.ObjectNode) mapper.readTree("{\"revision\":\"1\",\"accessMode\":\"PREPARED\",\"effectiveFrom\":null,\"effectiveUntil\":null,\"limits\":{\"memberLimit\":10,\"groupLimit\":15,\"groupMemberLimit\":10,\"storageBytes\":\"214748364800\",\"agentLimit\":50,\"parallelTaskLimit\":5}}");
        result.setAll((com.fasterxml.jackson.databind.node.ObjectNode) mapper.readTree(override));
        return result;
    }

    @Test void acceptsLiteralOverviewInitialPolicyAndPreservesPackageProfile() throws Exception {
        var initial = policy("{}");
        transaction.executeWithoutResult(status -> service.prepare(11, initial));
        assertEquals("1", service.projection(11).desiredRevision());
        assertFalse(service.projection(11).capabilities().get("memberLimit"));
        var snapshot = mapper.readTree(jdbc.queryForObject("SELECT params_value FROM byai.tenant_config WHERE enterprise_id=11 AND params_code='PACKAGE_CONTENT_SNAPSHOT'", String.class));
        assertEquals("shared", snapshot.path("profileKey").asText());
        assertEquals(10, snapshot.path("memberLimit").asInt());
    }

    @BeforeEach void setup() {
        // Avoid PostgreSQL compatibility mode: it would hide unsupported ON CONFLICT writes.
        var source = new DriverManagerDataSource("jdbc:h2:mem:policy" + System.nanoTime() + ";DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE SCHEMA byai");
        jdbc.execute("CREATE TABLE byai.tenant_config(id BIGINT GENERATED BY DEFAULT AS IDENTITY,enterprise_id BIGINT,params_code VARCHAR(64),params_value VARCHAR(1024),params_version BIGINT DEFAULT 0)");
        jdbc.execute("CREATE TABLE byai.tenant_execution_policy(enterprise_id BIGINT,revision BIGINT,payload TEXT NOT NULL,PRIMARY KEY(enterprise_id,revision))");
        jdbc.execute("CREATE TABLE byai.tenant_policy_cursor(enterprise_id BIGINT PRIMARY KEY,desired_revision BIGINT NOT NULL,generation VARCHAR(64) NOT NULL)");
        jdbc.execute("CREATE TABLE byai.tenant_policy_consumer(enterprise_id BIGINT,policy_revision BIGINT,consumer_key VARCHAR(64),generation VARCHAR(64),applied_at TIMESTAMP WITH TIME ZONE,PRIMARY KEY(enterprise_id,policy_revision,consumer_key,generation))");
        for (long id : new long[]{11,12,13}) {
            jdbc.update("INSERT INTO byai.tenant_config(enterprise_id,params_code,params_value) VALUES (?,'COMMERCIAL_MANAGED','true')", id);
            jdbc.update("INSERT INTO byai.tenant_config(enterprise_id,params_code,params_value) VALUES (?,'PACKAGE_CONTENT_SNAPSHOT','{\"profileKey\":\"shared\",\"memberLimit\":10}')", id);
        }
        transaction = new TransactionTemplate(new DataSourceTransactionManager(source));
        service = new TenantExecutionPolicyService(jdbc, mapper, false,
            Clock.fixed(Instant.parse("2026-10-26T00:00:00Z"), ZoneOffset.UTC));
    }

    @Test void preparedCannotExecuteEvenWhenGlobalEnforcementDisabled() throws Exception {
        var policy = policy("{\"accessMode\":\"PREPARED\"}");
        transaction.executeWithoutResult(status -> service.prepare(11, policy));
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class, () -> service.requireExecution(11));
        assertEquals("PREPARED", service.projection(11).accessMode());
    }

    @Test void missingIsDeniedWhenEnforcementEnabledAndExemptionIsDeploymentOnly() throws Exception {
        service = new TenantExecutionPolicyService(jdbc, mapper, true, Clock.systemUTC());
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class, () -> service.requireExecution(12));
        var policy = policy("{\"accessMode\":\"PREPARED\"}");
        transaction.executeWithoutResult(status -> service.prepare(12, policy));
        var exempt = policy("{\"accessMode\":\"EXEMPT\"}");
        assertThrows(IllegalArgumentException.class, () -> transaction.executeWithoutResult(status -> service.update(12, 1, exempt)));
        service = new TenantExecutionPolicyService(jdbc, mapper, true, Clock.systemUTC(), java.util.Set.of(12L));
        assertDoesNotThrow(() -> service.requireExecution(12));
    }

    @Test void expiredPolicyIsDenied() throws Exception {
        var policy = policy("{\"accessMode\":\"PREPARED\",\"effectiveUntil\":\"2026-10-25T00:00:00Z\"}");
        transaction.executeWithoutResult(status -> service.prepare(12, policy));
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class, () -> service.requireExecution(12));
    }

    @Test void disabledCompatibilityNeverQueriesNewPolicyTablesForUnmanagedTenant() {
        jdbc.execute("DROP TABLE byai.tenant_execution_policy");
        jdbc.execute("DROP TABLE byai.tenant_policy_cursor");
        assertDoesNotThrow(() -> service.requireExecution(99));
    }

    @Test void staleRevisionCannotOverwriteAndRollbackRemovesPreparation() throws Exception {
        var policy = policy("{\"accessMode\":\"PREPARED\"}");
        transaction.executeWithoutResult(status -> service.prepare(12, policy));
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class,
            () -> transaction.executeWithoutResult(status -> service.update(12, 0, policy)));
        assertEquals("1", service.projection(12).desiredRevision());
        transaction.executeWithoutResult(status -> { service.prepare(13, policy); status.setRollbackOnly(); });
        assertNull(service.projection(13).desiredRevision());
    }

    @Test void concurrentRevisionCannotReplaceCommittedSuccessor() throws Exception {
        var initial = policy("{}");
        transaction.executeWithoutResult(status -> service.prepare(12, initial));
        var successor = policy("{\"revision\":\"2\",\"accessMode\":\"SUSPENDED\"}");
        transaction.executeWithoutResult(status -> service.update(12, 1, successor));
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class,
            () -> transaction.executeWithoutResult(status -> service.update(12, 1, successor)));
        assertEquals("2", service.projection(12).desiredRevision());
        assertEquals("SUSPENDED", service.projection(12).accessMode());
    }

    @Test void rejectsIncompleteLimitsAndWrongSuccessorRevision() throws Exception {
        var initial = policy("{}");
        transaction.executeWithoutResult(status -> service.prepare(12, initial));
        assertThrows(IllegalArgumentException.class,
            () -> transaction.executeWithoutResult(status -> service.update(12, 1, initial)));
        var incomplete = policy("{\"limits\":{\"memberLimit\":10}}");
        assertThrows(IllegalArgumentException.class,
            () -> transaction.executeWithoutResult(status -> service.prepare(13, incomplete)));
    }

    @Test void staleGenerationAndUnsupportedNodeCannotAcknowledge() throws Exception {
        var policy = policy("{\"accessMode\":\"PREPARED\"}");
        transaction.executeWithoutResult(status -> service.prepare(12, policy));
        transaction.executeWithoutResult(status -> service.setGeneration(12, "2"));
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class,
            () -> transaction.executeWithoutResult(status -> service.acknowledge(12, 1, "1", "main-service")));
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class,
            () -> transaction.executeWithoutResult(status -> service.acknowledge(12, 1, "2", "node")));
        transaction.executeWithoutResult(status -> service.acknowledge(12, 1, "2", "main-service"));
        assertFalse(service.projection(12).fullyApplied());
    }

    @Test void repeatedAcknowledgementPreservesOriginalTimestampAndSeparatesGenerations() throws Exception {
        var initial = policy("{}");
        transaction.executeWithoutResult(status -> {
            service.prepare(12, initial);
            service.setGeneration(12, "1");
            service.acknowledge(12, 1, "1", "main-service");
        });
        var firstApplied = jdbc.queryForObject("SELECT applied_at FROM byai.tenant_policy_consumer WHERE enterprise_id=12",
            java.sql.Timestamp.class);
        var later = new TenantExecutionPolicyService(jdbc, mapper, false,
            Clock.fixed(Instant.parse("2026-10-27T00:00:00Z"), ZoneOffset.UTC));
        transaction.executeWithoutResult(status -> later.acknowledge(12, 1, "1", "main-service"));
        assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM byai.tenant_policy_consumer WHERE enterprise_id=12", Integer.class));
        assertEquals(firstApplied, jdbc.queryForObject("SELECT applied_at FROM byai.tenant_policy_consumer WHERE enterprise_id=12",
            java.sql.Timestamp.class));
        transaction.executeWithoutResult(status -> {
            later.setGeneration(12, "2");
            later.acknowledge(12, 1, "2", "main-service");
        });
        assertEquals(2, jdbc.queryForObject("SELECT count(*) FROM byai.tenant_policy_consumer WHERE enterprise_id=12", Integer.class));
    }

    @Test void unsupportedActivationAndUnknownQuotaAreRejected() throws Exception {
        var prepared = policy("{\"accessMode\":\"PREPARED\"}");
        transaction.executeWithoutResult(status -> service.prepare(12, prepared));
        var active = policy("{\"revision\":\"2\",\"accessMode\":\"ENABLED\",\"effectiveFrom\":\"2026-10-25T00:00:00Z\",\"effectiveUntil\":\"2026-11-25T00:00:00Z\"}");
        assertThrows(TenantExecutionPolicyService.PolicyDeniedException.class,
            () -> transaction.executeWithoutResult(status -> service.update(12, 1, active)));
        var unknown = policy("{\"accessMode\":\"PREPARED\",\"limits\":{\"inventedQuota\":10}}");
        assertThrows(IllegalArgumentException.class,
            () -> transaction.executeWithoutResult(status -> service.prepare(13, unknown)));
    }
}
